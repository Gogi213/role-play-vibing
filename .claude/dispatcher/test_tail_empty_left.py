"""E-011 (TK-060): «Осталось: ничего» / «Осталось: нет» / «не осталось ничего» — отрицание пустого остатка — считалось хвостом
(TK-059, приёмка тега). Гасится только законченный оборот; «Осталось: ничего, кроме …», «Осталось: нет метрик» и прочее
«осталось» — по-прежнему хвост. Падает на f2cf497, проходит после."""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_tail_not_left import tail_hit  # noqa: E402


class TailEmptyLeftTests(unittest.TestCase):
    def test_empty_left_is_not_a_tail(self):
        for text in ("Осталось: ничего", "Осталось: ничего.", "осталось — ничего", "Осталось - ничего!", "Осталось: нет",
                     "Осталось: нет.", "осталось нет", "Не осталось ничего", "не осталось ничего.",
                     "Итог 947b120: 1400 passed. Алгоритм: регэксп. Осталось: ничего.",
                     "[итог: pr] PR #170@72c27a2 — всё сделано. Осталось: ничего\nАлгоритм: регэксп",
                     "Сделано, не осталось ничего"):
            with self.subTest(text=text):
                self.assertIsNone(tail_hit(text))

    def test_real_left_is_still_a_tail(self):
        for text in ("Осталось: тесты", "Осталось: нет метрик у 431 строки", "Осталось: ничего, кроме экспорта",
                     "Осталось: ничего не проверено", "Осталось: ничего. Не сделано: экспорт", "Не осталось ничего, кроме экспорта",
                     "Не осталось времени доделать экспорт", "Осталось: нет; экспорт", "Не сделано: экспорт", "Не достигнуто: 3 из 5",
                     "Осталось: ничего. Хвост: экспорт", "Осталось: ничего или экспорт"):
            with self.subTest(text=text):
                self.assertIsNotNone(tail_hit(text))


if __name__ == "__main__":
    unittest.main()
